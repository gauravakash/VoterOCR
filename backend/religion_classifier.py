# ---------------------------------------------------------------------------
# Tokenization
# ---------------------------------------------------------------------------

# Split on whitespace, comma, semicolon, slash, parens, dash, ZWJ, ZWNJ, danda.
_TOKEN_SPLIT = re.compile(r"[\s,;/()\[\]\-–—।॥‌‍]+")


def _tokenize(text: str) -> list[str]:
    if not text:
        return []
    text = text.strip()
    raw = _TOKEN_SPLIT.split(text)
    out = []
    for t in raw:
        t = t.strip()
        if not t:
            continue
        out.append(t)
        # Also yield variants without trailing punctuation like "मो." → "मो"
        stripped = t.rstrip(".।॥०0o")
        if stripped and stripped != t:
            out.append(stripped)
    return out


# ---------------------------------------------------------------------------
# Scoring
# ---------------------------------------------------------------------------

def _score(tokens: Iterable[str]) -> dict[str, int]:
    s = {"Muslim": 0, "Hindu": 0, "Sikh": 0}
    for tok in tokens:
        if tok in MUSLIM_STRONG:
            s["Muslim"] += 3
        elif tok in MUSLIM_WEAK:
            s["Muslim"] += 1
        if tok in HINDU_STRONG:
            s["Hindu"] += 3
        elif tok in HINDU_WEAK:
            s["Hindu"] += 1
        if tok in SIKH_STRONG:
            s["Sikh"] += 3
    return s


def _winner(scores: dict[str, int]) -> Tuple[Optional[str], int, int]:
    """Return (top_label, top_score, runner_up_score)."""
    items = sorted(scores.items(), key=lambda kv: kv[1], reverse=True)
    top_label, top_score = items[0]
    runner = items[1][1] if len(items) > 1 else 0
    if top_score == 0:
        return None, 0, 0
    return top_label, top_score, runner


def classify(name: Optional[str], relative_name: Optional[str] = None) -> Tuple[str, str]:
    """Classify a voter as Hindu / Muslim / Sikh / Unknown.

    Returns (religion, confidence). Confidence is High / Medium / Low.
    """
    name_tokens = _tokenize(name or "")
    rel_tokens = _tokenize(relative_name or "")

    name_scores = _score(name_tokens)
    rel_scores = _score(rel_tokens)

    name_top, name_top_s, name_runner = _winner(name_scores)
    rel_top, rel_top_s, rel_runner = _winner(rel_scores)

    # Case 1: name itself has a clear winner with strong markers
    if name_top and name_top_s >= 3 and name_top_s > name_runner:
        # If runner is also strong (>=3), call it Medium
        if name_runner >= 3:
            confidence = "Medium"
        else:
            confidence = "High"
        # Cross-check with relative if relative votes for a different religion strongly
        if rel_top and rel_top != name_top and rel_top_s >= 6:
            confidence = "Medium"
        return name_top, confidence

    # Case 2: name has weak signal, relative has strong signal → use relative
    if rel_top and rel_top_s >= 3 and rel_top_s > rel_runner:
        # Names of relatives in Indian voter rolls are usually father/husband.
        # Religion is family-level so this is a reliable tiebreaker.
        confidence = "Medium" if rel_top_s >= 6 else "Medium"
        return rel_top, confidence

    # Case 3: name has weak (1-2 score) signal, no strong relative signal
    if name_top and name_top_s >= 1 and name_top_s > name_runner:
        return name_top, "Low"

    # Case 4: only relative signal is weak
    if rel_top and rel_top_s >= 1 and rel_top_s > rel_runner:
        return rel_top, "Low"

    return "Unknown", "Low"


